"""2-D airfoil RANS case: the section-level discriminator for the rotor gap.

PURPOSE. Rung 1 showed the rotor CFD is 41-47% low on CT even with a clean,
converged wake, so the suspect moved from the wake to the SECTION. This module
runs the same section, the same turbulence model and the same wall treatment as
the rotor case, in 2-D, so the only thing being tested is the section modelling.

WHAT IS HELD IDENTICAL TO THE ROTOR CASE (this is the whole point):
  * the section geometry — `geometry.section_polygon(DEFAULT_SECTION, ...)` with
    the same finite trailing edge, i.e. literally the profile the blade is
    lofted from, not a textbook NACA 4412;
  * turbulence model (kOmegaSST) and wall treatment (nutkWallFunction), with the
    first-cell height chosen to land y+ in the rotor's measured 11-83 band;
  * fvSchemes and fvSolution, copied from the rotor writer;
  * rho and nu.

ONE MESH, EVERY ANGLE. The airfoil is fixed and the FREESTREAM is rotated, so a
single mesh serves the whole alpha sweep and no per-alpha meshing error can
masquerade as an alpha trend. That works because the far field uses
freestreamVelocity/freestreamPressure, which decide inflow vs outflow
face-by-face from the local flux and so accept any freestream direction.

MESHER. cartesian2DMesh (cfMesh, bundled with ESI OpenFOAM). snappyHexMesh
cannot be used: its octree refines isotropically and would split the span
direction, breaking the one-cell-thick 2-D assumption. cfMesh emits every patch
as `empty`, so the patch types are rewritten after meshing — see
`fix_boundary_types`.
"""
from __future__ import annotations

from dataclasses import dataclass

import numpy as np

from ..contracts import SolverError
from ..geometry import DEFAULT_SECTION, SectionFn, section_polygon
from .openfoam import _wsl_sh, write_dict
from .wsl import _quote

RHO_AIR = 1.225
NU_AIR = 1.4607e-5


@dataclass(frozen=True)
class AirfoilCaseConfig:
    chord_m: float = 0.0287           # rotor mid-span chord
    far_field_chords: float = 25.0
    dz_frac: float = 0.1              # span thickness / chord (2-D, arbitrary)
    max_cell_frac: float = 2.0        # background cell / chord
    # ABSOLUTE wall-normal spacing, and absolute for the same reason
    # HoverCaseConfig.first_layer_m is: relative sizing ties the wall cell to
    # the local refinement level, so the y+ it produces moves with the mesh
    # instead of staying where it was put. y+ is evaluated at the cell CENTRE,
    # so the wall cell contributes about half its height: 4.5e-4 m puts y+ at
    # roughly 10 (Re 2e4) to 30 (Re 7e4), which brackets good5's measured mean
    # of 28 and sits inside the rotor's 11-83 band.
    surface_cell_m: float = 4.5e-4
    # NO boundary layers, mirroring the rotor case (n_layers=0). An earlier
    # attempt with 10 layers and maxFirstLayerThickness=2e-4 silently produced
    # y+ ~ 1: cfMesh compresses the layer stack into the available surface
    # cell, so the requested first-layer thickness never bound and the case was
    # wall-RESOLVED while still using a log-layer wall function.
    n_layers: int = 0
    layer_ratio: float = 1.2
    first_layer_m: float = 2.0e-4
    nut_wall_function: str = "nutkWallFunction"
    turbulence_model: str = "kOmegaSST"
    rho: float = RHO_AIR
    nu: float = NU_AIR
    n_chord: int = 121
    te_thickness_m: float = 2.0e-4    # same finite TE the blade loft uses


def _ribbon(contour: np.ndarray, name: str, dz: float) -> str:
    """Extrude a closed 2-D contour into an STL solid (a 'ribbon').

    cfMesh's 2-D mesher wants the domain boundary as a surface that is constant
    along the span; front/back faces are generated by the mesher itself.
    """
    out = [f"solid {name}"]
    n = len(contour)
    for i in range(n):
        a, b = contour[i], contour[(i + 1) % n]
        quad = [((a[0], a[1], 0.0), (b[0], b[1], 0.0), (b[0], b[1], dz)),
                ((a[0], a[1], 0.0), (b[0], b[1], dz), (a[0], a[1], dz))]
        for tri in quad:
            out.append(" facet normal 0 0 0\n  outer loop")
            for p in tri:
                out.append("   vertex %.9g %.9g %.9g" % p)
            out.append("  endloop\n endfacet")
    out.append(f"endsolid {name}")
    return "\n".join(out)


def build_airfoil_mesh_case(case, cfg: AirfoilCaseConfig,
                            section: SectionFn = DEFAULT_SECTION) -> dict:
    src = case.src
    c = cfg.chord_m
    dz = cfg.dz_frac * c
    poly = section_polygon(section, cfg.n_chord, cfg.te_thickness_m / c) * c
    poly = poly - np.array([0.25 * c, 0.0])       # quarter-chord at the origin
    L = cfg.far_field_chords * c
    box = np.array([(-L, -L), (L, -L), (L, L), (-L, L)])
    (src / "geom.stl").parent.mkdir(parents=True, exist_ok=True)
    (src / "geom.stl").write_text(_ribbon(box, "farfield", dz) + "\n"
                                  + _ribbon(poly, "airfoil", dz) + "\n")

    layers = "" if cfg.n_layers <= 0 else f"""
boundaryLayers
{{
    patchBoundaryLayers
    {{
        "airfoil"
        {{
            nLayers                 {cfg.n_layers};
            thicknessRatio          {cfg.layer_ratio};
            maxFirstLayerThickness  {cfg.first_layer_m:.8g};
            allowDiscontinuity      0;
        }}
    }}
    optimiseLayer 1;
}}
"""
    write_dict(src, "system", "meshDict", f"""
surfaceFile     "geom.stl";
maxCellSize     {cfg.max_cell_frac * c:.8g};
boundaryCellSize {8.0 * cfg.surface_cell_m:.8g};
localRefinement {{ "airfoil" {{ cellSize {cfg.surface_cell_m:.8g}; }} }}
{layers}""")
    _write_static_dicts(src, cfg)
    return {"chord_m": c, "dz": dz, "poly_points": int(len(poly)),
            "far_field_m": L}


def fix_boundary_types(case) -> None:
    """cfMesh emits EVERY patch as `empty`, including the wall and the far
    field. Rewrite the two real patches; the auto-generated front/back
    (`*EmptyFaces`) must stay `empty` for a 2-D run."""
    bfile = case.work + "/constant/polyMesh/boundary"
    txt = _wsl_sh("cat " + _quote(bfile)).stdout
    if not txt.strip():
        raise SolverError("could not read polyMesh/boundary after meshing")
    for name, typ in (("airfoil", "wall"), ("farfield", "patch")):
        new, n = _retype(txt, name, typ)
        if n != 1:
            raise SolverError(f"expected exactly one `{name}` patch to retype, "
                              f"found {n}")
        txt = new
    _wsl_sh("cat > " + _quote(bfile) + " <<'PROPOPT_EOF'\n" + txt
            + "\nPROPOPT_EOF")


def _retype(txt: str, name: str, typ: str):
    """Replace the `type` of the named patch block only."""
    out, n, i = [], 0, 0
    lines = txt.splitlines()
    while i < len(lines):
        out.append(lines[i])
        if lines[i].strip() == name:
            depth = 0
            i += 1
            while i < len(lines):
                s = lines[i]
                depth += s.count("{") - s.count("}")
                if s.strip().startswith("type"):
                    indent = s[:len(s) - len(s.lstrip())]
                    out.append(f"{indent}type {typ};")
                    n += 1
                else:
                    out.append(s)
                if depth == 0:
                    break
                i += 1
        i += 1
    return "\n".join(out), n


def write_airfoil_fields(src, cfg: AirfoilCaseConfig, u_inf: float,
                         alpha_deg: float) -> dict:
    """0/ fields for one operating point. The airfoil is FIXED; the freestream
    is rotated by alpha, so lift is not aligned with a mesh axis and is
    recovered by rotating the integrated force in post."""
    a = np.radians(alpha_deg)
    ux, uy = u_inf * np.cos(a), u_inf * np.sin(a)
    uvec = f"({ux:.9g} {uy:.9g} 0)"
    # Same discipline as the rotor advancing case: I = 1%, nu_t/nu = 1.
    k_inf = 1.5 * (0.01 * u_inf) ** 2
    omega_inf = k_inf / cfg.nu
    eps_inf = 0.09 * k_inf ** 2 / cfg.nu

    write_dict(src, "0", "U", f"""
dimensions      [0 1 -1 0 0 0 0];
internalField   uniform {uvec};
boundaryField
{{
    airfoil  {{ type noSlip; }}
    farfield {{ type freestreamVelocity; freestreamValue uniform {uvec}; }}
    ".*EmptyFaces" {{ type empty; }}
}}
""", cls="volVectorField")
    write_dict(src, "0", "p", """
dimensions      [0 2 -2 0 0 0 0];
internalField   uniform 0;
boundaryField
{
    airfoil  { type zeroGradient; }
    farfield { type freestreamPressure; freestreamValue uniform 0; }
    ".*EmptyFaces" { type empty; }
}
""", cls="volScalarField")
    write_dict(src, "0", "k", f"""
dimensions      [0 2 -2 0 0 0 0];
internalField   uniform {k_inf:.8g};
boundaryField
{{
    airfoil  {{ type kqRWallFunction; value uniform {k_inf:.8g}; }}
    farfield {{ type inletOutlet; inletValue uniform {k_inf:.8g};
               value uniform {k_inf:.8g}; }}
    ".*EmptyFaces" {{ type empty; }}
}}
""", cls="volScalarField")
    write_dict(src, "0", "omega", f"""
dimensions      [0 0 -1 0 0 0 0];
internalField   uniform {omega_inf:.8g};
boundaryField
{{
    airfoil  {{ type omegaWallFunction; value uniform {omega_inf:.8g}; }}
    farfield {{ type inletOutlet; inletValue uniform {omega_inf:.8g};
               value uniform {omega_inf:.8g}; }}
    ".*EmptyFaces" {{ type empty; }}
}}
""", cls="volScalarField")
    write_dict(src, "0", "epsilon", f"""
dimensions      [0 2 -3 0 0 0 0];
internalField   uniform {eps_inf:.8g};
boundaryField
{{
    airfoil  {{ type epsilonWallFunction; value uniform {eps_inf:.8g}; }}
    farfield {{ type inletOutlet; inletValue uniform {eps_inf:.8g};
               value uniform {eps_inf:.8g}; }}
    ".*EmptyFaces" {{ type empty; }}
}}
""", cls="volScalarField")
    write_dict(src, "0", "nuTilda", f"""
dimensions      [0 2 -1 0 0 0 0];
internalField   uniform {3.0 * cfg.nu:.6e};
boundaryField
{{
    airfoil  {{ type fixedValue; value uniform 0; }}
    farfield {{ type inletOutlet; inletValue uniform {3.0 * cfg.nu:.6e};
               value uniform {3.0 * cfg.nu:.6e}; }}
    ".*EmptyFaces" {{ type empty; }}
}}
""", cls="volScalarField")
    write_dict(src, "0", "nut", f"""
dimensions      [0 2 -1 0 0 0 0];
internalField   uniform 0;
boundaryField
{{
    airfoil  {{ type {cfg.nut_wall_function}; value uniform 0; }}
    farfield {{ type calculated; value uniform 0; }}
    ".*EmptyFaces" {{ type empty; }}
}}
""", cls="volScalarField")
    return {"u_inf": u_inf, "alpha_deg": alpha_deg, "k_inf": k_inf,
            "omega_inf": omega_inf, "re": cfg.rho * u_inf * cfg.chord_m
            / (cfg.rho * cfg.nu)}


def _write_static_dicts(src, cfg: AirfoilCaseConfig) -> None:
    write_dict(src, "constant", "transportProperties",
               f"transportModel  Newtonian;\nnu              {cfg.nu:.8g};\n")
    write_dict(src, "constant", "turbulenceProperties", f"""
simulationType  RAS;
RAS
{{
    RASModel        {cfg.turbulence_model};
    turbulence      on;
    printCoeffs     on;
}}
""")
    # fvSchemes / fvSolution copied from the rotor writer so the numerics under
    # test are the rotor's numerics, not a 2-D-tuned variant.
    write_dict(src, "system", "fvSchemes", """
ddtSchemes      { default steadyState; }
gradSchemes     { default cellLimited Gauss linear 1; }
divSchemes
{
    default         none;
    div(phi,U)      bounded Gauss linearUpwind grad(U);
    div(phi,k)      bounded Gauss limitedLinear 1;
    div(phi,omega)  bounded Gauss limitedLinear 1;
    div(phi,epsilon) bounded Gauss limitedLinear 1;
    div(phi,nuTilda) bounded Gauss limitedLinear 1;
    div((nuEff*dev2(T(grad(U))))) Gauss linear;
}
laplacianSchemes { default Gauss linear limited corrected 0.33; }
interpolationSchemes { default linear; }
snGradSchemes   { default limited corrected 0.33; }
wallDist        { method meshWave; }
""")
    write_dict(src, "system", "fvSolution", """
solvers
{
    p { solver GAMG; tolerance 1e-08; relTol 0.01; smoother GaussSeidel; }
    Phi { solver GAMG; tolerance 1e-07; relTol 0.01; smoother GaussSeidel; }
    "(U|k|omega|epsilon|nuTilda)"
    { solver smoothSolver; smoother symGaussSeidel; tolerance 1e-08; relTol 0.01; }
}
SIMPLE
{
    nNonOrthogonalCorrectors 1;
    consistent      yes;
    // Turbulence residuals are held to 1e-5, not 1e-6: k stalls around 1e-4
    // long after the FORCES have stopped moving, and force stationarity is the
    // convergence measure that matters here (it is what the rotor case used).
    residualControl { p 1e-6; U 1e-6; "(k|omega|epsilon|nuTilda)" 1e-5; }
}
relaxationFactors { equations { ".*" 0.9; } }
""")


def write_run_control(src, cfg: AirfoilCaseConfig, n_iter: int) -> None:
    write_dict(src, "system", "controlDict", f"""
application     simpleFoam;
startFrom       startTime;   startTime 0;
stopAt          endTime;     endTime {n_iter};
deltaT          1;
writeControl    timeStep;    writeInterval {n_iter};
purgeWrite      2;
writeFormat     ascii;       writePrecision 8;  writeCompression off;
timeFormat      general;     timePrecision 6;
runTimeModifiable true;

functions
{{
    forces
    {{
        type            forces;
        libs            (forces);
        patches         (airfoil);
        rho             rhoInf;
        rhoInf          {cfg.rho};
        CofR            (0 0 0);
        writeControl    timeStep;
        writeInterval   1;
    }}
    yplus
    {{
        type            yPlus;
        libs            (fieldFunctionObjects);
        writeControl    writeTime;
    }}
}}
""")
